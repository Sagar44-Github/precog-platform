def _make_events(spec, hosts, outgoing, routes, seed):
    rng = random.Random(seed ^ 0x3C6EF372)
    by_id = {item["host_id"]: item for item in hosts}
    events = []
    ports = {"web-server": 443, "database-server": 5432, "domain-controller": 389,
             "file-server": 445, "backup-server": 22, "workstation": 443}
    for index in range(spec["benign_events"]):
        source = hosts[rng.randrange(len(hosts))]["host_id"]
        choices = sorted(outgoing[source])
        if not choices:
            continue
        target = rng.choice(choices)
        target_role = by_id[target]["role"]
        events.append({"t": index * 7 + rng.randrange(7), "src": source, "dst": target, "kind": "traffic",
                       "severity": "NORMAL", "label": "benign", "attack_class": None,
                       "protocol": rng.choice(("TCP", "TCP", "UDP")), "port": ports.get(target_role, 443),
                       "bytes": rng.randint(64, 1500), "extra": {"traffic_class": "generated-background", "simulated": True}})
    base_time = spec["benign_events"] * 7 + 1000
    for campaign, route in enumerate(routes[:spec["campaigns"]]):
        for hop, target in enumerate(route["path"]):
            source = route["path"][hop - 1] if hop else None
            events.append({"t": base_time + campaign * 500 + hop * 30, "src": source, "dst": target,
                           "kind": "technique" if hop == 0 else "attempt", "severity": "HIGH",
                           "label": "simulated-initial-access" if hop == 0 else "simulated-lateral-movement",
                           "attack_class": "simulated-access" if hop == 0 else "simulated-lateral-movement",
                           "protocol": "TCP", "port": ports.get(by_id[target]["role"], 443),
                           "bytes": 1024, "extra": {"campaign": campaign + 1, "profile": route["profile"], "route_id": route["route_id"], "simulated": True}})
    events.sort(key=lambda item: (item["t"], item["src"] or "", item["dst"], item["kind"], item["label"] or ""))
    for index, event in enumerate(events, 1):
        event["event_id"] = index
    return events


def _write_sqlite(path, hosts, assets, edges, events, routes, scenario):
    counts = {}
    for event in events:
        if event["src"] is not None and event["dst"] is not None:
            key = (event["src"], event["dst"])
            counts[key] = counts.get(key, 0) + 1
    conn = sqlite3.connect(path)
    try:
        conn.executescript("""
            PRAGMA journal_mode=DELETE;
            PRAGMA synchronous=FULL;
            CREATE TABLE hosts(host_id TEXT PRIMARY KEY, display_name TEXT NOT NULL, zone TEXT NOT NULL, role TEXT NOT NULL, criticality REAL NOT NULL, details_json TEXT NOT NULL);
            CREATE TABLE edges(src TEXT NOT NULL, dst TEXT NOT NULL, edge_kind TEXT NOT NULL, count INTEGER NOT NULL, first_seen INTEGER, last_seen INTEGER, provenance TEXT NOT NULL, PRIMARY KEY(src,dst,edge_kind));
            CREATE TABLE events(event_id INTEGER PRIMARY KEY, t INTEGER NOT NULL, src TEXT, dst TEXT, kind TEXT NOT NULL, severity TEXT, label TEXT, attack_class TEXT, protocol TEXT, port INTEGER, bytes INTEGER, extra_json TEXT NOT NULL);
            CREATE TABLE routes(route_id TEXT PRIMARY KEY, label TEXT NOT NULL, hops_json TEXT NOT NULL, provenance TEXT NOT NULL);
            CREATE TABLE labels(label_id INTEGER PRIMARY KEY, event_id INTEGER, label TEXT NOT NULL, provenance TEXT NOT NULL);
            CREATE TABLE windows(window_id TEXT PRIMARY KEY, title TEXT NOT NULL, start_t INTEGER NOT NULL, end_t INTEGER NOT NULL, scenario_file TEXT NOT NULL);
            CREATE INDEX idx_events_t ON events(t);
            CREATE INDEX idx_events_src ON events(src);
            CREATE INDEX idx_events_dst ON events(dst);
        """)
        for host in hosts:
            detail = {"simulated": True, "services": assets[host["host_id"]]["services"],
                      "decoy": assets[host["host_id"]]["decoy"]}
            conn.execute("INSERT INTO hosts VALUES(?,?,?,?,?,?)", (host["host_id"], host["name"], host["zone"], host["role"],
                         assets[host["host_id"]]["criticality"], json.dumps(detail, sort_keys=True, separators=(",", ":"))))
        for edge in edges:
            observed = counts.get((edge["src"], edge["dst"]), 0)
            conn.execute("INSERT INTO edges VALUES(?,?,?,?,?,?,?)", (edge["src"], edge["dst"], "feasible", observed,
                         min((e["t"] for e in events if e["src"] == edge["src"] and e["dst"] == edge["dst"]), default=None),
                         max((e["t"] for e in events if e["src"] == edge["src"] and e["dst"] == edge["dst"]), default=None),
                         "native-generated-simulation"))
        for event in events:
            conn.execute("INSERT INTO events VALUES(?,?,?,?,?,?,?,?,?,?,?,?)", (event["event_id"], event["t"], event["src"], event["dst"],
                         event["kind"], event["severity"], event["label"], event["attack_class"], event["protocol"], event["port"],
                         event["bytes"], json.dumps(event["extra"], sort_keys=True, separators=(",", ":"))))
            if event["label"] is not None:
                conn.execute("INSERT INTO labels(event_id,label,provenance) VALUES(?,?,?)",
                             (event["event_id"], event["label"], "native-generated-simulation"))
        for route in routes:
            hops = [{"host_id": host_id, "position": position} for position, host_id in enumerate(route["path"])]
            conn.execute("INSERT INTO routes VALUES(?,?,?,?)", (route["route_id"], route["profile"],
                         json.dumps(hops, sort_keys=True, separators=(",", ":")), route["provenance"]))
        conn.execute("INSERT INTO windows VALUES(?,?,?,?,?)", (scenario["scenario_id"], scenario["description"], 0,
                     max(event["offset_ms"] for event in scenario["events"]), "scenarios/%s.json" % scenario["scenario_id"]))
        conn.commit()
        conn.execute("VACUUM")
    finally:
        conn.close()


def _evaluation_contract_record(pack_id, seed, result, limitations):
    model = result["node_model"]
    baseline_rule = result["baseline_rule_based"]
    baseline_uniform = result["baseline_uniform"]
    metrics = {
        "forecasts": model["forecasts"], "precision_at_1": model["precision_at_1"],
        "precision_at_1_std_error": model["precision_at_1_std_error"], "precision_at_3": model["precision_at_3"],
        "mean_reciprocal_rank": model["mean_reciprocal_rank"], "expected_calibration_error": model["expected_calibration_error"],
        "max_candidates": model["max_candidates"], "share_with_more_than_3_candidates": model["share_with_more_than_3_candidates"],
    }
    def score_record(score):
        return {key: score[key] for key in ("forecasts", "precision_at_1", "precision_at_1_std_error", "precision_at_3",
                                            "mean_reciprocal_rank", "expected_calibration_error", "max_candidates",
                                            "share_with_more_than_3_candidates")}
    baselines = {"rule_based": score_record(baseline_rule), "uniform": score_record(baseline_uniform)}
    split = {"method": "seeded-random-route", "training_routes": result["split"]["training_sequences"],
             "test_routes": result["split"]["test_sequences"], "test_forecasts": result["split"]["test_forecasts"]}
    return {
        "workspace_id": pack_id, "seed": seed, "split": split, "metrics": metrics, "baselines": baselines,
        "route_provenance": result["route_provenance"], "calibration_bins": model["calibration_bins"],
        "candidate_set_distribution": result["candidate_set_distribution"], "profile_metrics": result["by_profile"],
        "alpha": result["alpha"], "limitations": list(limitations),
    }


def _evaluation_inputs(pack_dir):
    topology = _read_json(pack_dir / "topology.json")
    routes = [json.loads(line) for line in (pack_dir / "routes.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
    if len(routes) < 5 or any(len(route.get("path", [])) < 2 for route in routes):
        raise PackError("At least five non-empty multi-host routes are required for a held-out evaluation")
    legacy = {"feasible_connections": {host["host_id"]: [] for host in topology["hosts"]}, "assets": topology["assets"]}
    for edge in topology["feasible_edges"]:
        legacy["feasible_connections"].setdefault(edge["src"], []).append(edge["dst"])
    # Use the product's topology implementation so edge likelihoods match replay and the demo baseline.
    from graph_net.topology import Topology
    graph = Topology(topology["hosts"], legacy)
    candidates = lambda here, path: graph.candidates(here, exclude=path)
    return routes, graph, candidates


def _evaluate_pack_contents(pack_dir, contracts_dir=None, seed=None, test_fraction=0.2, route_provenance="simulated", limitations=None):
    pack_dir = Path(pack_dir).resolve()
    manifest = validate_pack(pack_dir, contracts_dir, require_matching_dir=False)
    routes, graph, candidates = _evaluation_inputs(pack_dir)
    seed = int(manifest["seed"] if seed is None else seed)
    model, result = evaluate(routes, candidates, graph.edge_probability, seed=seed, test_fraction=test_fraction, extended_metrics=True)
    full_model = NodeModel.train(routes, result["alpha"]["chosen"], meta={
        "workspace_id": manifest["id"], "generator_seed": manifest["seed"], "evaluation_seed": seed,
        "training_routes": len(routes), "routes_sha256": _sha(pack_dir / "routes.jsonl"),
        "alpha_chosen_on": "held-out evaluation's training-only validation split",
        "model_type": "first-order Markov node transition model",
    })
    model_doc = full_model.to_dict()
    (pack_dir / "model.json").write_bytes(_canonical_json(model_doc))
    limitations = list(LIMITATIONS if limitations is None else limitations)
    result.update({"source": EVALUATOR_VERSION, "training_routes_sha256": _sha(pack_dir / "routes.jsonl"),
                   "route_provenance": route_provenance, "limitations": limitations})
    summary = _evaluation_contract_record(manifest["id"], seed, result, limitations)
    schema = _read_json(Path(contracts_dir or Path(__file__).resolve().parents[3] / "contracts") / "schemas" / "evaluation_result.schema.json")
    errors = sorted(Draft202012Validator(schema).iter_errors(summary), key=lambda err: list(err.path))
    if errors:
        raise PackError("Generated evaluation result violates its contract: %s" % errors[0].message)
    result["evaluation_result"] = summary
    (pack_dir / "evaluation.json").write_bytes(_canonical_json(result))
    updated_manifest = dict(manifest)
    digest, size_bytes = _payload_hash(pack_dir)
    updated_manifest["content_hash"] = digest
    updated_manifest["size_bytes"] = size_bytes
    (pack_dir / "manifest.json").write_bytes(_canonical_json(updated_manifest))
    validate_pack(pack_dir, contracts_dir, require_matching_dir=False)
    return updated_manifest, result


def evaluate_pack(pack_dir, contracts_dir=None, seed=None, test_fraction=0.2):
    """Re-evaluate a pack on a staged copy and atomically replace it on success."""
    pack_dir = Path(pack_dir).resolve()
    if not pack_dir.is_dir() or pack_dir.is_symlink():
        raise PackError("Pack directory does not exist or is a symbolic link")
    validate_pack(pack_dir, contracts_dir)
    parent = pack_dir.parent
    staging = Path(tempfile.mkdtemp(prefix=".%s-evaluate-" % pack_dir.name, dir=str(parent)))
    backup = parent / (".%s-evaluate-backup" % pack_dir.name)
    try:
        staging.rmdir()
        shutil.copytree(pack_dir, staging)
        manifest, result = _evaluate_pack_contents(staging, contracts_dir, seed, test_fraction)
        if backup.exists():
            shutil.rmtree(backup)
        os.replace(pack_dir, backup)
        try:
            os.replace(staging, pack_dir)
        except Exception:
            if backup.exists() and not pack_dir.exists():
                os.replace(backup, pack_dir)
            raise
        shutil.rmtree(backup, ignore_errors=True)
        return manifest, result
    finally:
        if staging.exists():
            shutil.rmtree(staging, ignore_errors=True)


