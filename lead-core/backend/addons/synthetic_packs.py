def _hosts_and_assets(pack_id, spec, seed):
    rng = random.Random(seed)
    hosts, assets, zone_hosts = [], {}, {}
    ordinal = 0
    for zone_index, (zone, count) in enumerate(spec["zones"].items(), 1):
        zone_hosts[zone] = []
        choices = spec["roles"][zone]
        for _ in range(count):
            ordinal += 1
            role = choices[rng.randrange(len(choices))]
            host_id = "node-%04d" % ordinal
            address = "10.%d.%d.%d" % (zone_index, ordinal // 254, ordinal % 254 + 1)
            display = "%s %03d" % (role.replace("-", " ").title(), len(zone_hosts[zone]) + 1)
            is_decoy = ordinal % 17 == 0
            criticality = round(0.35 + rng.random() * 0.60, 2)
            if role in ("database-server", "domain-controller", "backup-server", "object-store", "orchestrator"):
                criticality = round(max(criticality, 0.80), 2)
            services = SERVICE_MAP.get(role, ["https/443"])
            cvss = round(5.0 + rng.random() * 4.9, 1)
            weakness = {"id": "DEMO-SIM-%06d" % ordinal, "cvss": cvss, "service": services[0],
                        "description": "Simulated service weakness generated for this replay; not a real vulnerability."}
            hosts.append({"host_id": host_id, "name": display, "zone": zone, "address": address, "role": role})
            zone_hosts[zone].append(host_id)
            assets[host_id] = {"services": list(services), "criticality": criticality, "decoy": is_decoy, "vulns": [weakness]}
    if len(hosts) != spec["hosts"]:
        raise PackError("Synthetic zone sizes do not match the pack host count")
    return hosts, assets, zone_hosts


def _topology_edges(spec, hosts, assets, zone_hosts, seed):
    rng = random.Random(seed ^ 0xA5A55A5A)
    host_by_id = {item["host_id"]: item for item in hosts}
    outgoing = {item["host_id"]: set() for item in hosts}
    for source in hosts:
        source_id = source["host_id"]
        pool = []
        for target_zone in spec["zone_targets"][source["zone"]]:
            pool.extend(zone_hosts[target_zone])
        peer_pool = [host_id for host_id in zone_hosts[source["zone"]] if host_id != source_id]
        if peer_pool:
            pool.extend(rng.sample(peer_pool, min(len(peer_pool), max(1, spec["fanout"] // 3))))
        pool = sorted(set(pool) - {source_id})
        if not pool:
            pool = sorted(set(host_by_id) - {source_id})
        degree = min(len(pool), spec["fanout"])
        if degree:
            outgoing[source_id].update(rng.sample(pool, degree))
    edges = []
    for source in sorted(outgoing):
        for target in sorted(outgoing[source]):
            vulnerability = max((float(v.get("cvss", 0)) for v in assets[target].get("vulns", [])), default=0.0)
            edges.append({"src": source, "dst": target, "probability": round(vulnerability / 10.0, 4)})
    return outgoing, edges


def _make_routes(pack_id, spec, hosts, zone_hosts, outgoing, seed):
    rng = random.Random(seed ^ 0x5A5AA5A5)
    host_by_id = {item["host_id"]: item for item in hosts}
    profiles = sorted(spec["starts"])
    routes = []
    for index in range(spec["route_count"]):
        profile = profiles[index % len(profiles)]
        starts = [host_id for zone in spec["starts"][profile] for host_id in zone_hosts[zone]]
        route = None
        for _attempt in range(80):
            current = rng.choice(starts)
            path = [current]
            max_hops = rng.randint(3, 6)
            for _ in range(max_hops - 1):
                candidates = [target for target in sorted(outgoing[current]) if target not in path]
                if not candidates:
                    break
                target_candidates = [target for target in candidates if host_by_id[target]["zone"] in spec["goals"]]
                # Keep routes varied while making many campaigns reach sensitive tiers.
                target = rng.choice(target_candidates if target_candidates and len(path) >= 2 and rng.random() < 0.65 else candidates)
                path.append(target)
                current = target
                if len(path) >= 3 and host_by_id[current]["zone"] in spec["goals"]:
                    break
            if len(path) >= 3:
                route = path
                break
        if route is None:
            raise PackError("Could not produce a multi-stage route for %s" % profile)
        routes.append({"route_id": "%s-route-%05d" % (pack_id, index + 1), "profile": profile,
                       "path": route, "provenance": "native-generated-simulation"})
    return routes


