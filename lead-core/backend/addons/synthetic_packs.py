def build_synthetic_pack(repo_root, pack_id, output_dir=None, seed=None, contracts_dir=None):
    """Build one small, deterministic generated pack; no raw or external data is read."""
    repo_root = Path(repo_root).resolve()
    if pack_id not in SPECS:
        raise PackError("Unknown synthetic pack id %r" % pack_id)
    spec = SPECS[pack_id]
    seed = int(spec["seed"] if seed is None else seed)
    if seed < 0 or seed > 2**31 - 1:
        raise PackError("Synthetic seed must be between 0 and 2147483647")
    output_dir = Path(output_dir or repo_root / "packs" / pack_id).resolve()
    if output_dir.name != pack_id:
        raise PackError("Output directory must be named %s" % pack_id)
    parent = output_dir.parent
    parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=".%s-build-" % pack_id, dir=str(parent)))
    backup = parent / (".%s-backup" % pack_id)
    try:
        hosts, assets, zone_hosts = _hosts_and_assets(pack_id, spec, seed)
        outgoing, feasible_edges = _topology_edges(spec, hosts, assets, zone_hosts, seed)
        routes = _make_routes(pack_id, spec, hosts, zone_hosts, outgoing, seed)
        scenario = _make_scenario(pack_id, routes)
        events = _make_events(spec, hosts, outgoing, routes, seed)
        clusters = [{"id": "zone-" + zone, "name": zone, "host_ids": sorted(members)} for zone, members in zone_hosts.items()]
        observed_counts = {}
        for event in events:
            if event["src"] and event["dst"]:
                observed_counts[(event["src"], event["dst"])] = observed_counts.get((event["src"], event["dst"]), 0) + 1
        topology = {"network_id": pack_id, "hosts": hosts, "feasible_edges": feasible_edges,
                    "observed_edges": [{"src": src, "dst": dst, "count": count, "provenance": "native-generated-simulation"}
                                       for (src, dst), count in sorted(observed_counts.items())],
                    "assets": assets, "clusters": clusters}
        (staging / "topology.json").write_bytes(_canonical_json(topology))
        scenario_dir = staging / "scenarios"
        scenario_dir.mkdir()
        (scenario_dir / "campaign-preview.json").write_bytes(_canonical_json(scenario))
        route_lines = [json.dumps(route, sort_keys=True, separators=(",", ":")) for route in routes]
        (staging / "routes.jsonl").write_text("\n".join(route_lines) + "\n", encoding="utf-8", newline="\n")
        _write_sqlite(staging / "pack.sqlite", hosts, assets, feasible_edges, events, routes, scenario)
        full_model = NodeModel.train(routes, DEFAULT_ALPHA, meta={"workspace_id": pack_id, "generator_seed": seed, "model_type": "first-order Markov node transition model"})
        (staging / "model.json").write_bytes(_canonical_json(full_model.to_dict()))
        evaluation = _make_placeholder_evaluation(seed)
        (staging / "evaluation.json").write_bytes(_canonical_json(evaluation))
        card = """# {name}

This is a deterministic **SIMULATION** generated by {builder}. It contains no recorded network traffic, real vulnerabilities, or observed attacker behavior.

- Hosts: {hosts}; zones: {zones}; generated feasible links: {edges}.
- Training routes: {routes}; route truth is native to the generator and synthetic.
- Events: {events} generated background and campaign records; all labels are simulated.
- Detector modes: direct label playback (trivial ground-truth replay) or a first-seen-edge graph novelty estimate after a 20% warm-up window.
- Seed: `{seed}`. Rebuild with the same seed to reproduce this pack payload.
- Structure: {layout}. Services, DEMO-SIM weaknesses, campaign profiles, and multi-stage routes are generated for demonstration and controlled evaluation.
- Evaluation: route-level held-out evaluation, calibration, a rule-based ranking baseline, and a uniform ranking baseline. Results describe only this generator.

## Limitations

Do not interpret the metrics as real-world detection or protection performance. Containment and what-if results change only simulated state. `precision@3` may be inflated when the candidate set is small; read candidate-set sizes, precision@1, MRR, calibration, and the standard error together.
""".format(name=spec["name"], builder=GENERATOR_VERSION, hosts=len(hosts), zones=len(zone_hosts), edges=len(feasible_edges),
           routes=len(routes), events=len(events), seed=seed, layout=spec["layout"])
        (staging / "card.md").write_text(card, encoding="utf-8", newline="\n")
        manifest = {
            "id": pack_id, "name": spec["name"], "version": "1.0.0", "builder_version": GENERATOR_VERSION, "seed": seed,
            "created_at": REPRODUCIBLE_CREATED_AT,
            "source": {"id": "precog-synthetic-generator", "name": "Project-owned deterministic simulation generator",
                       "citation": "Project-owned simulation; cite Precog SOC and builder version.",
                       "licence": "Project-owned simulation", "terms_summary": "Generated project data; no external dataset or raw data is redistributed."},
            "redistribution": "project-owned", "size_bytes": 0,
            "counts": {"hosts": len(hosts), "edges": len(feasible_edges), "events": len(events),
                       "labelled_events": sum(1 for item in events if item["label"] is not None), "routes": len(routes),
                       "time_span_ms": max(item["t"] for item in events)},
            "capabilities": {"detection_labels": "native", "host_compromise": "native", "lateral_movement_routes": "native", "topology": "native"},
            "attack_classes": [{"id": "simulated-access", "compromise_semantics": "access-attempt"},
                               {"id": "simulated-lateral-movement", "compromise_semantics": "lateral-movement"},
                               {"id": "simulated-background", "compromise_semantics": "impact-only"}],
            "technique_mapping": [
                {"attack_class": "simulated-access", "technique_ids": ["T1110", "T1078"], "assumption": "Technique IDs are scripted labels selected by this simulation; they are not inferred observations."},
                {"attack_class": "simulated-lateral-movement", "technique_ids": ["T1021.001"], "assumption": "Lateral-movement labels describe generated route steps, not real actor behavior."},
            ],
            "detector_options": ["labels", "graph-novelty"],
            "default_decision_policy": {"mode": "scenario-pauses", "threshold": 0.0, "minimum_candidates": 1},
            "display_hints": {"zones": list(spec["zones"]), "clusters": "zone", "layout": spec["layout"]},
            "source_file_checksums": [{"path": "lead-core/backend/addons/synthetic_packs.py", "sha256": _sha(Path(__file__))}],
            "content_hash": "0" * 64,
        }
        digest, size_bytes = _payload_hash(staging)
        manifest["content_hash"], manifest["size_bytes"] = digest, size_bytes
        (staging / "manifest.json").write_bytes(_canonical_json(manifest))
        validate_pack(staging, contracts_dir or repo_root / "contracts", require_matching_dir=False)
        _evaluate_pack_contents(staging, contracts_dir or repo_root / "contracts", seed=seed)
        validate_pack(staging, contracts_dir or repo_root / "contracts", require_matching_dir=False)
        if output_dir.exists():
            if backup.exists():
                shutil.rmtree(backup)
            os.replace(output_dir, backup)
        try:
            os.replace(staging, output_dir)
        except Exception:
            if backup.exists() and not output_dir.exists():
                os.replace(backup, output_dir)
            raise
        if backup.exists():
            shutil.rmtree(backup)
        return validate_pack(output_dir, contracts_dir or repo_root / "contracts")
    finally:
        if staging.exists():
            shutil.rmtree(staging, ignore_errors=True)
