"""Regenerate a compact evaluation table from installed workspace packs."""
from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
for folder in ("lead-core/backend", "lead-core/precog", "graph"):
    sys.path.insert(0, str(ROOT / folder))

from addons.dataset_packs import PackStore  # noqa: E402
from addons.synthetic_packs import evaluate_pack  # noqa: E402


def _evaluation_on_copy(pack_path, contracts_dir, work_root):
    manifest = json.loads((pack_path / "manifest.json").read_text(encoding="utf-8"))
    copy_path = work_root / manifest["id"]
    shutil.copytree(pack_path, copy_path)
    _, result = evaluate_pack(copy_path, contracts_dir, seed=manifest.get("seed", 0), test_fraction=0.2)
    return manifest, result["evaluation_result"]


def render_results(root=ROOT):
    root = Path(root).resolve()
    contracts = root / "contracts"
    packs_root = root / "packs"
    registry = json.loads((root / "datasets" / "registry.json").read_text(encoding="utf-8"))
    installed = {item["id"]: item for item in PackStore(packs_root, contracts).list_packs()}
    rows = []
    with tempfile.TemporaryDirectory(prefix="precog-cross-eval-") as temp:
        work_root = Path(temp)
        for dataset in registry["workspaces"]:
            pack_id = dataset["id"]
            if pack_id not in installed:
                rows.append((dataset, None))
                continue
            manifest, evaluation = _evaluation_on_copy(packs_root / pack_id, contracts, work_root)
            rows.append((dataset, {"manifest": manifest, "evaluation": evaluation}))

    lines = [
        "# Cross-dataset workspace results",
        "",
        "Generated by `python tools/datasets/build_cross_dataset_results.py`. Installed packs are re-evaluated on temporary copies with their manifest seed; source packs are not changed.",
        "",
        "All installed metrics below are estimates on scripted or synthetic route sequences. They do not measure detection or forecasting on real attacker behavior. Registered datasets without a local pack are listed with no metrics and were not evaluated.",
        "",
        "| Workspace | Availability | Hosts | Events | Routes | Markov P@1 ± SE | Rule P@1 | Uniform P@1 | P@3 | ECE | Data basis |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for dataset, output in rows:
        pack_id = dataset["id"]
        if output is None:
            values = (dataset["status"], "—", "—", "—", "—", "—", "—", "—", "—")
        else:
            manifest = output["manifest"]
            result = output["evaluation"]
            metrics = result["metrics"]
            values = (
                "installed",
                str(manifest["counts"]["hosts"]),
                str(manifest["counts"]["events"]),
                str(result["split"]["test_routes"]),
                "%.4f ± %.4f" % (metrics["precision_at_1"], metrics["precision_at_1_std_error"]),
                "%.4f" % result["baselines"]["rule_based"]["precision_at_1"],
                "%.4f" % result["baselines"]["uniform"]["precision_at_1"],
                "%.4f" % metrics["precision_at_3"],
                "%.4f" % metrics["expected_calibration_error"],
            )
        basis = "project-generated simulation" if dataset["redistribution_status"] == "project-owned" else "not installed; source/licence gate pending"
        lines.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (pack_id, *values, basis))
    lines.extend([
        "",
        "P@3 is often trivial for small candidate sets; interpret it with the listed candidate-space limits and prioritize P@1, its standard error, calibration, and the baselines. The six-host demo's shipped headline evaluation is reported separately in `lead-core/precog/results/precog_evaluation.json` and remains the fixed parity reference.",
        "",
    ])
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "docs" / "CROSS_DATASET_RESULTS.md")
    args = parser.parse_args(argv)
    output = args.output if args.output.is_absolute() else ROOT / args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    content = render_results().encode("utf-8")
    handle, temporary = tempfile.mkstemp(prefix=".cross-dataset-", suffix=".tmp", dir=str(output.parent))
    try:
        with os.fdopen(handle, "wb") as stream:
            stream.write(content)
        os.replace(temporary, output)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    print("Wrote %s" % output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
